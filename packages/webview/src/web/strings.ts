export type WebT = (key: WebKey, params?: Record<string, string | number>) => string;

export function webT(locale: string): WebT {
  const table = locale.toLowerCase().startsWith("zh") ? zh : en;
  return (key, params) => table[key].replace(/\{(\w+)\}/g, (_m, name: string) => String(params?.[name] ?? `{${name}}`));
}
