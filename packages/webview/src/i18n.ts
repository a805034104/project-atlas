export type Lang = "en" | "zh";
export const TABLES: Record<Lang, Record<StringKey, string>> = { en, zh };

export function langFor(locale: string | undefined): Lang {
  return locale?.toLowerCase().startsWith("zh") ? "zh" : "en";
}

export type Params = Record<string, string | number>;
export type Translate = (key: StringKey, params?: Params) => string;

export function makeT(lang: Lang): Translate {
  const table = TABLES[lang];
  return (key, params) => {
    const s = table[key];
    if (!params) return s;
    return s.replace(/\{(\w+)\}/g, (m, name: string) => (name in params ? String(params[name]) : m));
  };
}

export interface I18n {
  lang: Lang;
  t: Translate;
}

export const I18nContext = createContext<I18n>({ lang: "en", t: makeT("en") });

export function useI18n(): I18n {
  return useContext(I18nContext);
}
