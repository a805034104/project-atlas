/**
 * ATLAS.md export (spec E1): a committed-friendly, deterministic summary of
 * an AtlasGraph. Pure function of the graph — same graph, same bytes.
 *
 *   AtlasGraph ─▶ header (project, analyzedAt UTC, analyzer version)
 *     ─▶ Overview ─▶ Services ─▶ Features (AI) ─▶ How to run (startup, file:line)
 *     ─▶ Modules ─▶ Cross-service links (aggregated) ─▶ Request flows (GraphView.flowDetail)
 *     ─▶ Unresolved calls ─▶ footer (atlas:generated marker)
 *
 * Plain CommonMark only: no HTML. Free text is backslash-escaped, identifiers
 * and paths go into code spans, so symbol names like `<select id="x">` never
 * render as markup.
 */

export type MarkdownLanguage = "zh-cn" | "en";

export interface MarkdownOptions {
  language?: MarkdownLanguage;
  /** HTTP entrypoints whose flows are listed (default 20). */
  maxFlows?: number;
}

export const DEFAULT_MAX_FLOWS = 20;
const MAX_UNRESOLVED = 10;
const MAX_FEATURE_ENTRYPOINTS = 10;

