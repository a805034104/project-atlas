/** Backslash-escape free text so it cannot form markup (incl. HTML) or break a table cell. */
export function escapeMarkdown(text: string): string {
  return text
    .replace(/\r?\n+/g, " ")
    .replace(/[\\`*_[\]<>|#]/g, (ch) => `\\${ch}`)
    .trim();
}

/** Inline code span that survives backticks in the content. */
export function codeSpan(text: string): string {
  const flat = text.replace(/\r?\n+/g, " ");
  const longest = Math.max(0, ...[...flat.matchAll(/`+/g)].map((m) => m[0].length));
  const fence = "`".repeat(longest + 1);
  const pad = flat.startsWith("`") || flat.endsWith("`") ? " " : "";
  return `${fence}${pad}${flat}${pad}${fence}`;
}

function table(header: readonly string[], rows: readonly string[][]): string[] {
  return [`| ${header.join(" | ")} |`, `|${header.map(() => " --- ").join("|")}|`, ...rows.map((r) => `| ${r.join(" | ")} |`)];
}

function fencedBlock(lines: readonly string[], lang = "sh"): string[] {
  const longest = Math.max(2, ...lines.flatMap((l) => [...l.matchAll(/`+/g)].map((m) => m[0].length)));
  const fence = "`".repeat(longest + 1);
  return [`${fence}${lang}`, ...lines, fence];
}

function compareServices(a: Service, b: Service): number {
  return cmp(a.name, b.name) || cmp(a.path, b.path) || cmp(a.id, b.id);
}

export function renderAtlasMarkdown(graph: AtlasGraph, options: MarkdownOptions = {}): string {
  const t = STRINGS[options.language ?? "en"];
  const maxFlows = Math.max(0, options.maxFlows ?? DEFAULT_MAX_FLOWS);
  const fmt = createRefFormatter(graph);
  const at = (ref: SourceRef) => codeSpan(fmt(ref));
  const view = new GraphView(graph);
  const serviceName = new Map(graph.services.map((s) => [s.id, s.name]));
  const nameOf = (id: string) => serviceName.get(id) ?? id;
  const out: string[] = [];
  const section = (heading: string) => out.push("", `## ${heading}`, "");

  // ── Header ────────────────────────────────────────────────────────────────
  out.push(`# ${t.title} — ${escapeMarkdown(graph.project.name)}`, "", `> ${t.generated(graph.analyzerVersion, graph.project.analyzedAt)}`);

  // ── Overview ──────────────────────────────────────────────────────────────
  section(t.overview);
  const http = graph.entrypoints.filter((e) => e.kind === "http");
  const stacks = [...graph.project.stacks].sort(cmp);
  out.push(`- ${t.stacks}: ${stacks.length > 0 ? stacks.map(codeSpan).join(", ") : "—"}`);
  out.push(
    `- ${t.counts({
      services: graph.services.length,
      modules: graph.modules.length,
      http: http.length,
      routes: graph.entrypoints.filter((e) => e.kind === "frontend-route").length,
      links: graph.serviceLinks.length,
      unresolved: graph.unresolvedCalls.length,
    })}`,
  );
  out.push(`- ${t.ai(aiUsageText(graph))}`);

  // ── Services ──────────────────────────────────────────────────────────────
  section(t.services);
  const services = [...graph.services].sort(compareServices);
  if (services.length === 0) out.push(t.noServices);
  else {
    const servicePath = (s: Service) => fmt({ rootId: s.rootId, file: s.path }).replace(/\/$/, "") || ".";
    out.push(...table(t.serviceCols, services.map((s) => [escapeMarkdown(s.name), s.kind, s.stack, codeSpan(servicePath(s))])));
  }

  // ── Features ──────────────────────────────────────────────────────────────
  section(t.features);
  if (graph.features.length === 0) out.push(t.noFeatures);
  else {
    const moduleName = new Map(graph.modules.map((m) => [m.id, m.name]));
    const entrypoints = new Map(graph.entrypoints.map((e) => [e.id, e]));
    const features = [...graph.features].sort((a, b) => cmp(a.tier, b.tier) || cmp(a.title, b.title) || cmp(a.id, b.id));
    for (const f of features) {
      out.push(`### ${escapeMarkdown(f.title)} (${f.tier})`, "");
      if (f.description) out.push(escapeMarkdown(f.description), "");
      const mods = f.moduleIds.map((id) => moduleName.get(id)).filter((n): n is string => !!n).sort(cmp);
      if (mods.length > 0) out.push(`- ${t.featureModules}: ${mods.map(codeSpan).join(", ")}`);
      const eps = f.entrypointIds.map((id) => entrypoints.get(id)).filter((e): e is Entrypoint => !!e).sort(compareEntrypoints);
      if (eps.length > 0) {
        const more = eps.length > MAX_FEATURE_ENTRYPOINTS ? ` (+${eps.length - MAX_FEATURE_ENTRYPOINTS})` : "";
        out.push(`- ${t.featureEntrypoints}: ${eps.slice(0, MAX_FEATURE_ENTRYPOINTS).map((e) => codeSpan(entrypointLabel(e))).join(", ")}${more}`);
      }
      out.push("");
    }
    if (out[out.length - 1] === "") out.pop();
  }

  // ── How to run ────────────────────────────────────────────────────────────
  section(t.run);
  const guides = [...graph.startup].sort((a, b) => cmp(a.target, b.target) || cmp(a.serviceId ?? "", b.serviceId ?? ""));
  if (guides.length === 0) out.push(t.noRun);
  for (const [i, g] of guides.entries()) {
    if (i > 0) out.push("");
    out.push(`### ${escapeMarkdown(g.target)}`);
    if (g.prerequisites.length > 0) {
      out.push("", `**${t.prerequisites}**`, "");
      for (const p of g.prerequisites) out.push(`- ${escapeMarkdown(p.name)}${p.version ? ` ${codeSpan(p.version)}` : ""} — ${at(p.evidence)}`);
    }
    if (g.steps.length > 0) {
      out.push("", `**${t.commands}**`);
      for (const s of g.steps) out.push("", t.runIn(s.cwd || ".", at(s.evidence)), "", ...fencedBlock([s.command]));
    }
    if (g.ports.length > 0) {
      out.push("", `**${t.ports}**`, "");
      for (const p of [...g.ports].sort((a, b) => a.port - b.port)) out.push(`- ${p.port} — ${at(p.evidence)}`);
    }
    if (g.configFiles.length > 0) {
      out.push("", `**${t.configFiles}**`, "");
      for (const f of [...g.configFiles].map(fmt).sort(cmp)) out.push(`- ${codeSpan(f)}`);
    }
  }

  // ── Modules ───────────────────────────────────────────────────────────────
  section(t.modules);
  const commits = view.commits90d();
  const modules = [...graph.modules].sort((a, b) => cmp(nameOf(a.serviceId), nameOf(b.serviceId)) || cmp(a.path, b.path) || cmp(a.name, b.name) || cmp(a.id, b.id));
  if (modules.length === 0) out.push(t.noModules);
  else {
    out.push(
      ...table(
        t.moduleCols,
        modules.map((m) => [
          escapeMarkdown(m.name),
          escapeMarkdown(nameOf(m.serviceId)),
          String(m.fileCount),
          String(m.loc),
          commits[m.id] === undefined ? "—" : String(commits[m.id]),
          m.summary ? escapeMarkdown(m.summary) : "—",
        ]),
      ),
    );
  }

  // ── Cross-service links ───────────────────────────────────────────────────
  section(t.links);
  const linkCounts = new Map<string, { from: string; to: string; kind: string; count: number }>();
  for (const l of graph.serviceLinks) {
    const from = nameOf(l.fromServiceId);
    const to = nameOf(l.toServiceId);
    const key = `${from}\0${to}\0${l.kind}`;
    const entry = linkCounts.get(key) ?? { from, to, kind: l.kind, count: 0 };
    entry.count++;
    linkCounts.set(key, entry);
  }
  const links = [...linkCounts.values()].sort((a, b) => cmp(a.from, b.from) || cmp(a.to, b.to) || cmp(a.kind, b.kind));
  if (links.length === 0) out.push(t.noLinks);
  else out.push(...table(t.linkCols, links.map((l) => [escapeMarkdown(l.from), escapeMarkdown(l.to), l.kind, String(l.count)])));

  // ── Request flows ─────────────────────────────────────────────────────────
  section(t.flows);
  const sortedHttp = [...http].sort(compareEntrypoints);
  if (sortedHttp.length === 0) out.push(t.noFlows);
  else {
    const shown = sortedHttp.slice(0, maxFlows);
    out.push(t.flowsShown(shown.length, sortedHttp.length));
    for (const ep of shown) {
      out.push("", `### ${codeSpan(entrypointLabel(ep))} · ${escapeMarkdown(nameOf(ep.serviceId))}`, "");
      const detail = view.flowDetail(ep.id);
      if (!detail || detail.steps.length === 0) {
        out.push(`${t.noSteps} ${at(ep.handler)}`);
        continue;
      }
      const multi = detail.services.length > 1;
      detail.steps.forEach((s, i) => {
        const service = multi ? ` · ${escapeMarkdown(nameOf(s.serviceId))}` : "";
        out.push(`${i + 1}. ${s.layer} · ${codeSpan(s.symbol.name)} (${at(s.symbol)})${service}`);
      });
      if (detail.flow.truncated) out.push("", `_${t.truncated}_`);
    }
  }

  // ── Unresolved calls ──────────────────────────────────────────────────────
  section(t.unresolved);
  out.push(t.unresolvedCount(graph.unresolvedCalls.length));
  if (graph.unresolvedCalls.length > 0) {
    const groups = new Map<string, { expression: string; reason: string; count: number; first: string }>();
    for (const u of graph.unresolvedCalls) {
      const key = `${u.expression}\0${u.reason}`;
      const where = fmt(u.at);
      const g = groups.get(key);
      if (!g) groups.set(key, { expression: u.expression, reason: u.reason, count: 1, first: where });
      else {
        g.count++;
        if (cmp(where, g.first) < 0) g.first = where;
      }
    }
    const top = [...groups.values()].sort((a, b) => b.count - a.count || cmp(a.expression, b.expression) || cmp(a.reason, b.reason)).slice(0, MAX_UNRESOLVED);
    out.push("", ...table(t.unresolvedCols, top.map((g) => [codeSpan(g.expression), g.reason, String(g.count), codeSpan(g.first)])));
  }

  out.push("", "---", "", `_${t.footer}_`, "");
  return out.join("\n");
}

function aiUsageText(graph: AtlasGraph): string | undefined {
  if (graph.llmUsage.length === 0) return undefined;
  const models = [...new Set(graph.llmUsage.map((u) => `${u.provider}/${u.model}`))].sort(cmp);
  const input = graph.llmUsage.reduce((n, u) => n + u.inputTokens, 0);
  const output = graph.llmUsage.reduce((n, u) => n + u.outputTokens, 0);
  return `${models.map(codeSpan).join(", ")} — ${input} in / ${output} out tokens`;
}
