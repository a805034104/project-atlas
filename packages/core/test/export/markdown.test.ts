const R = "root1";
const ref = (file: string, line?: number) => (line === undefined ? { rootId: R, file } : { rootId: R, file, line });
const sym = (name: string, file: string, line: number) => ({ ...ref(file, line), name, fqn: `x.${name}` });

/** Two services, one HTTP flow crossing a Feign link, one unresolved call. */
function smallGraph(): AtlasGraph {
  const g = emptyGraph("0.1.0", "shop", new Date("2026-10-15T08:00:00Z"));
  g.project.roots = [{ id: R, path: "/repos/shop", kind: "workspace" }];
  g.project.stacks = ["vue", "java-spring"];
  g.services = [
    { id: "s-order", name: "order", rootId: R, path: "order", stack: "java-spring", kind: "backend", evidence: ref("order/App.java", 3) },
    { id: "s-user", name: "user", rootId: R, path: "user", stack: "java-spring", kind: "backend", evidence: ref("user/App.java", 3) },
  ];
  g.modules = [
    { id: "m-user", serviceId: "s-user", name: "user", path: "user", kind: "build-module", dependsOn: [], fileCount: 4, loc: 120 },
    { id: "m-order", serviceId: "s-order", name: "order", path: "order", kind: "build-module", dependsOn: [], fileCount: 7, loc: 300, summary: "Orders | payments" },
  ];
  g.history = [
    {
      moduleId: "m-order",
      commits: [
        { sha: "a", authorTime: "2026-10-01T00:00:00Z", author: "x", message: "m", added: 1, deleted: 0, files: [] },
        { sha: "b", authorTime: "2025-01-01T00:00:00Z", author: "x", message: "m", added: 1, deleted: 0, files: [] },
      ],
    },
  ];
  g.startup = [
    {
      target: "order",
      serviceId: "s-order",
      prerequisites: [{ name: "JDK", version: "17", evidence: ref("pom.xml", 9) }],
      steps: [{ command: "mvn -pl order spring-boot:run", cwd: ".", evidence: ref("order/pom.xml", 40) }],
      ports: [{ port: 8081, evidence: ref("order/application.yml", 2) }],
      configFiles: [ref("order/application.yml")],
    },
  ];
  g.entrypoints = [
    { id: "e-create", serviceId: "s-order", kind: "http", method: "POST", path: "/order", handler: sym("OrderController.create", "order/OrderController.java", 20) },
    { id: "e-info", serviceId: "s-user", kind: "http", method: "GET", path: "/user/info/{}", handler: sym("UserController.info", "user/UserController.java", 11) },
  ];
  g.steps = [
    { id: "st1", serviceId: "s-order", layer: "controller", symbol: sym("OrderController.create", "order/OrderController.java", 20) },
    { id: "st2", serviceId: "s-order", layer: "service", symbol: sym("OrderService.create", "order/OrderService.java", 30) },
    { id: "st3", serviceId: "s-user", layer: "controller", symbol: sym("UserController.info", "user/UserController.java", 11) },
    { id: "st4", serviceId: "s-user", layer: "sql", symbol: sym('<select id="selectUser">', "user/UserMapper.xml", 5) },
  ];
  g.edges = [
    { id: "ed1", from: "st1", to: "st2", order: 0, provenance: "static", confidence: 1 },
    { id: "ed2", from: "st2", to: "st3", order: 0, provenance: "framework-rule", confidence: 1 },
    { id: "ed3", from: "st3", to: "st4", order: 0, provenance: "framework-rule", confidence: 1 },
  ];
  g.flows = [
    { entrypointId: "e-create", stepIds: ["st1", "st2", "st3", "st4"], edgeIds: ["ed1", "ed2", "ed3"], truncated: false },
    { entrypointId: "e-info", stepIds: ["st3", "st4"], edgeIds: ["ed3"], truncated: true },
  ];
  g.serviceLinks = [
    { id: "l1", fromServiceId: "s-order", toServiceId: "s-user", kind: "http", channel: "GET /user/info/{}", fromStepId: "st2", provenance: "framework-rule", confidence: 1, evidence: [] },
    { id: "l2", fromServiceId: "s-order", toServiceId: "s-user", kind: "http", channel: "GET /user/x", fromStepId: "st2", provenance: "framework-rule", confidence: 1, evidence: [] },
  ];
  g.unresolvedCalls = [
    { fromStepId: "st2", expression: "client.send(…)", reason: "unknown-receiver", at: ref("order/OrderService.java", 44) },
    { fromStepId: "st2", expression: "client.send(…)", reason: "unknown-receiver", at: ref("order/OrderService.java", 41) },
    { fromStepId: "st1", expression: "x.y()", reason: "dynamic-dispatch", at: ref("order/OrderController.java", 22) },
  ];
  return g;
}

describe("renderAtlasMarkdown", () => {
  it("renders every section from a hand-built graph", () => {
    const md = renderAtlasMarkdown(smallGraph());
    expect(md).toContain("# Project Atlas — shop");
    expect(md).toContain("Generated by ProjectAtlas 0.1.0 at 2026-10-15T08:00:00.000Z (UTC). atlas:generated v0.1.0");
    for (const h of ["## Overview", "## Services", "## Features", "## How to run", "## Modules", "## Cross-service links", "## Request flows", "## Unresolved calls"]) {
      expect(md).toContain(`\n${h}\n`);
    }
    expect(md).toContain("- Stacks: `java-spring`, `vue`");
    expect(md).toContain("AI was not run");
    // services sorted by name; modules sorted by service; summary escaped
    expect(md.indexOf("| order | backend")).toBeLessThan(md.indexOf("| user | backend"));
    expect(md).toContain("| order | order | 7 | 300 | 1 | Orders \\| payments |");
    expect(md).toContain("| user | user | 4 | 120 | — | — |");
    // startup with evidence and fenced command
    expect(md).toContain("- JDK `17` — `pom.xml:9`");
    expect(md).toContain("Run in `.` — evidence `order/pom.xml:40`\n\n```sh\nmvn -pl order spring-boot:run\n```");
    expect(md).toContain("- 8081 — `order/application.yml:2`");
    // links aggregated
    expect(md).toContain("| order | user | http | 2 |");
    // flows in path order, steps in flow order, symbol in code span (no raw HTML)
    expect(md.indexOf("### `POST /order` · order")).toBeLessThan(md.indexOf("### `GET /user/info/{}` · user"));
    expect(md).toContain("1. controller · `OrderController.create` (`order/OrderController.java:20`) · order");
    expect(md).toContain("4. sql · `<select id=\"selectUser\">` (`user/UserMapper.xml:5`) · user");
    expect(md).toContain("_Cut at the default depth");
    expect(md).not.toMatch(/(^|[^`\\])<select/m);
    // unresolved: grouped, ordered by count, first location
    expect(md).toContain("3 call(s) could not be resolved");
    expect(md).toContain("| `client.send(…)` | unknown-receiver | 2 | `order/OrderService.java:41` |");
    expect(md.trimEnd().endsWith("`project-atlas analyze --markdown ATLAS.md`._")).toBe(true);
  });

  it("is deterministic regardless of input order and honours maxFlows / language", () => {
    const a = smallGraph();
    const b = smallGraph();
    b.services.reverse();
    b.modules.reverse();
    b.entrypoints.reverse();
    b.serviceLinks.reverse();
    b.unresolvedCalls.reverse();
    expect(renderAtlasMarkdown(b)).toBe(renderAtlasMarkdown(a));

    const one = renderAtlasMarkdown(a, { maxFlows: 1 });
    expect(one).toContain("Showing 1 of 2 HTTP entrypoints");
    expect(one).not.toContain("### `GET /user/info/{}`");

    const zh = renderAtlasMarkdown(a, { language: "zh-cn" });
    for (const h of ["## 总览", "## 服务", "## 功能", "## 如何启动", "## 模块", "## 跨服务调用", "## 请求流转", "## 未解析调用"]) expect(zh).toContain(h);
    expect(zh).toContain("未运行 AI");
  });

  it("lists AI features when present", () => {
    const g = smallGraph();
    g.features = [{ id: "f1", title: "Checkout", description: "Place *orders*", tier: "core", moduleIds: ["m-order"], entrypointIds: ["e-create"] }];
    g.llmUsage = [{ provider: "anthropic", model: "claude-sonnet-5-5", phase: "features", inputTokens: 100, outputTokens: 20 }];
    const md = renderAtlasMarkdown(g);
    expect(md).toContain("### Checkout (core)\n\nPlace \\*orders\\*");
    expect(md).toContain("- Entrypoints: `POST /order`");
    expect(md).toContain("AI enrichment: `anthropic/claude-sonnet-5-5` — 100 in / 20 out tokens");
    expect(md).not.toContain("AI was not run");
  });

  it("escapes markup and code spans", () => {
    expect(escapeMarkdown("a|b <i>x</i>\nnext")).toBe("a\\|b \\<i\\>x\\</i\\> next");
    expect(codeSpan("a`b")).toBe("``a`b``");
  });

  it("finds entrypoints by id, label or path", () => {
    const g = smallGraph();
    expect(findEntrypoints(g, "e-info").map((e) => e.id)).toEqual(["e-info"]);
    expect(findEntrypoints(g, "get  /user/info/{}").map((e) => e.id)).toEqual(["e-info"]);
    expect(findEntrypoints(g, "/order").map((e) => e.id)).toEqual(["e-create"]);
    expect(findEntrypoints(g, "DELETE /nope")).toEqual([]);
  });
});

describe.skipIf(!haveFixtures(FIXTURES.ruoyiVue))("renderAtlasMarkdown on RuoYi-Vue", () => {
  it("contains the headings and the user list flow", async () => {
    const { graph } = await analyzeWorkspace({ roots: [{ path: FIXTURES.ruoyiVue }], history: false });
    const md = renderAtlasMarkdown(graph, { maxFlows: 1000 });
    for (const h of ["## Overview", "## Services", "## How to run", "## Modules", "## Request flows", "## Unresolved calls"]) expect(md).toContain(h);
    expect(md).toContain("| ruoyi-admin | backend | java-spring | `ruoyi-admin` |");
    expect(md).toContain("mvn -pl ruoyi-admin -am spring-boot:run");
    const start = md.indexOf("### `GET /system/user/list` · ruoyi-admin");
    expect(start).toBeGreaterThan(0);
    const flow = md.slice(start, md.indexOf("\n### ", start + 1));
    expect(flow).toMatch(/\d+\. controller · `SysUserController\.list` \(`ruoyi-admin\/src\/main\/java\/com\/ruoyi\/web\/controller\/system\/SysUserController\.java:\d+`\)/);
    expect(flow.indexOf("controller ·")).toBeLessThan(flow.indexOf("repository · `SysUserMapper.selectUserList`"));
    expect(flow).toContain('sql · `<select id="selectUserList">`');
    expect(renderAtlasMarkdown(graph, { maxFlows: 1000 })).toBe(md);
  }, 120_000);
});
